/**
 * Builds the redirect rules for every kind of host from one list (redirects.json):
 *   vercel.json                    (Vercel)
 *   deploy/htaccess                (Apache / most shared hosting: copy to .htaccess)
 *   deploy/nginx-redirects.conf    (nginx: include inside the server block)
 * The same rules work on S3/CloudFront through the guide in docs/HOSTING.md.
 *
 * An old address that is now a real page (for example a blog post that was brought over)
 * is skipped, so we never redirect a page to itself.
 */
import fs from 'node:fs';
import path from 'node:path';

const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const { redirects } = read('redirects.json');

// Addresses that now exist as real pages: blog posts.
let slugs = [];
try {
  slugs = read('src/data/wp-posts.json').map((p) => p.slug);
} catch {}
if (!slugs.length) {
  const seed = fs.readFileSync('src/data/legacyPosts.ts', 'utf8');
  slugs = [...seed.matchAll(/slug:\s*'([^']+)'/g)].map((m) => m[1]);
}
const live = new Set(slugs.map((s) => `/${s}`));
const active = redirects.filter((r) => !live.has(r.from));
const skipped = redirects.length - active.length;

// Vercel
const vercel = read('vercel.json');
vercel.redirects = active.flatMap((r) => [
  { source: `${r.from}/`, destination: r.to, statusCode: 301 },
  { source: r.from, destination: r.to, statusCode: 301 },
]);
fs.writeFileSync('vercel.json', JSON.stringify(vercel, null, 2) + '\n');

fs.mkdirSync('deploy', { recursive: true });

// Apache
const apache = [
  '# Generated by scripts/make-redirects.mjs. Do not edit by hand.',
  'RewriteEngine On',
  '',
  '# Old addresses',
  ...active.map((r) => `RewriteRule ^${r.from.replace(/^\//, '').replace(/[.]/g, '\\.')}/?$ ${r.to} [R=301,L]`),
  '',
  '# Always use a trailing slash on pages',
  'RewriteCond %{REQUEST_FILENAME} !-f',
  'RewriteCond %{REQUEST_URI} !\\.[a-zA-Z0-9]+$',
  'RewriteCond %{REQUEST_URI} !/$',
  'RewriteRule ^(.*)$ /$1/ [R=301,L]',
  '',
  'ErrorDocument 404 /404.html',
  '',
].join('\n');
fs.writeFileSync('deploy/htaccess', apache);

// nginx
const nginx = [
  '# Generated by scripts/make-redirects.mjs. Do not edit by hand.',
  '# Include inside the server { } block:  include /path/to/nginx-redirects.conf;',
  ...active.map((r) => `location = ${r.from} { return 301 ${r.to}; }\nlocation = ${r.from}/ { return 301 ${r.to}; }`),
  '',
].join('\n');
fs.writeFileSync('deploy/nginx-redirects.conf', nginx);

console.log(`[redirects] ${active.length} rules written (${skipped} skipped because the page now exists).`);
